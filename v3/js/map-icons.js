// Для canvas блипа (glImage в map.js): рисует значок обводкой в квадрате size×size с левым верхним углом (x, y).
// Пример: drawMapIcon(g, GL_KEY, 16, 16, 32, '#fff') вместо g.fillText(GL[k].ic, …).
export function drawMapIcon(g, name, x, y, size, color = '#fff', width = 1.8) {
  const src = MAP_ICONS[name];
  if (!src) return false;
  const k = size / 24;
  g.save();
  g.translate(x, y);
  g.scale(k, k);
  g.lineWidth = width;
  g.lineCap = 'round';
  g.lineJoin = 'round';
  g.strokeStyle = color;
  for (const m of src.matchAll(/ d="([^"]+)"/g)) g.stroke(new Path2D(m[1]));
  g.restore();
  return true;
}
